import type { NextConfig } from "next";

/**
 * Laravel is the authoritative backend. The browser talks to it through same-origin rewrites
 * (/backend/* and /sanctum/*) so Sanctum's cookie-based SPA authentication works without
 * cross-site cookies. Server components call the API directly via API_INTERNAL_URL.
 */
const apiOrigin = (process.env.API_INTERNAL_URL ?? "http://127.0.0.1:8010").replace(/\/$/, "");

const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  // Catalogue data comes from a live API, so pages use fetch revalidation (ISR) rather than
  // Cache Components prerendering, which would require the API at build time.
  cacheComponents: false,
  poweredByHeader: false,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  // Media renditions (WebP at 320–2400px) are generated by the backend and served with srcset,
  // so the Next image optimizer is not used for catalogue imagery.
  images: { unoptimized: true },
  async rewrites() {
    return [
      { source: "/backend/:path*", destination: `${apiOrigin}/:path*` },
      { source: "/sanctum/:path*", destination: `${apiOrigin}/sanctum/:path*` },
      { source: "/storage/:path*", destination: `${apiOrigin}/storage/:path*` },
    ];
  },
  async headers() {
    return [
      { source: "/:path*", headers: securityHeaders },
      { source: "/admin/:path*", headers: [{ key: "X-Frame-Options", value: "DENY" }, { key: "X-Robots-Tag", value: "noindex, nofollow" }] },
    ];
  },
};

export default nextConfig;
