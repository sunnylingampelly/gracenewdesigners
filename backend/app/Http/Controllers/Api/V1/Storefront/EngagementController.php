<?php

namespace App\Http\Controllers\Api\V1\Storefront;

use App\Http\Controllers\Controller;
use App\Models\AnalyticsEvent;
use App\Models\Category;
use App\Models\Collection;
use App\Models\Lookbook;
use App\Models\NewsletterSubscriber;
use App\Models\Occasion;
use App\Models\Page;
use App\Models\Product;
use App\Services\Settings\SettingsService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class EngagementController extends Controller
{
    public function newsletter(Request $request, SettingsService $settings): JsonResponse
    {
        abort_unless($settings->get('newsletter_enabled'), 404);
        $data = $request->validate([
            'email' => ['required', 'email:rfc', 'max:190'],
            'consent' => ['accepted'],
            'source' => ['nullable', 'string', 'max:60'],
            'website' => ['prohibited'],
        ], ['consent.accepted' => 'Please confirm you would like to receive our letters.']);

        $subscriber = NewsletterSubscriber::query()->firstOrNew(['email' => Str::lower($data['email'])]);
        $subscriber->fill([
            'source' => $data['source'] ?? 'footer',
            'consented_at' => now(),
            'unsubscribed_at' => null,
            'unsubscribe_token' => $subscriber->unsubscribe_token ?? Str::random(48),
        ])->save();

        // Identical response for new and existing addresses (no address enumeration).
        return response()->json(['data' => ['subscribed' => true]], 202);
    }

    public function unsubscribe(Request $request): JsonResponse
    {
        $token = (string) $request->validate(['token' => ['required', 'string', 'size:48']])['token'];
        NewsletterSubscriber::query()->where('unsubscribe_token', $token)->update(['unsubscribed_at' => now()]);

        return response()->json(['data' => ['unsubscribed' => true]]);
    }

    /**
     * First-party, consent-gated event collection. Only whitelisted events and non-personal
     * payload keys are stored; the session id is hashed with the app key.
     */
    public function track(Request $request): JsonResponse
    {
        $data = $request->validate([
            'events' => ['required', 'array', 'max:20'],
            'events.*.name' => ['required', Rule::in(array_diff(AnalyticsEvent::ALLOWED, ['whatsapp_enquiry_initiated']))],
            'events.*.product_id' => ['nullable', 'integer'],
            'events.*.path' => ['nullable', 'string', 'max:500'],
            'events.*.params' => ['nullable', 'array', 'max:10'],
            'events.*.params.*' => ['nullable', 'scalar', 'max:200'],
            'session_id' => ['nullable', 'string', 'max:64'],
        ]);

        $allowedParams = ['list_name', 'search_term', 'size', 'color', 'results', 'category', 'quantity'];
        $sessionHash = isset($data['session_id']) ? hash('sha256', $data['session_id'].config('app.key')) : null;

        foreach ($data['events'] as $event) {
            $productId = isset($event['product_id']) && Product::query()->whereKey($event['product_id'])->exists() ? $event['product_id'] : null;
            AnalyticsEvent::query()->create([
                'event_name' => $event['name'],
                'product_id' => $productId,
                'session_hash' => $sessionHash,
                'path' => isset($event['path']) ? parse_url($event['path'], PHP_URL_PATH) : null,
                'payload' => array_intersect_key($event['params'] ?? [], array_flip($allowedParams)) ?: null,
                'occurred_at' => now(),
            ]);
            if ($event['name'] === 'view_item' && $productId) {
                Product::withoutTimestamps(fn () => Product::query()->whereKey($productId)->increment('view_count'));
            }
        }

        return response()->json(null, 204);
    }

    /** URLs for the XML sitemap, generated by the storefront. Only indexable, published content. */
    public function sitemap(): JsonResponse
    {
        $products = Product::query()->publiclyVisible()->where('is_indexable', true)
            ->get(['slug', 'updated_at'])->map(fn ($p) => ['path' => '/products/'.$p->slug, 'updated_at' => $p->updated_at?->toIso8601String()]);
        $categories = Category::query()->published()->whereHas('department', fn ($q) => $q->where('is_active', true))
            ->get(['path', 'updated_at'])->map(fn ($c) => ['path' => '/shop/'.$c->path, 'updated_at' => $c->updated_at?->toIso8601String()]);
        $collections = Collection::query()->visible()->get(['slug', 'updated_at'])
            ->map(fn ($c) => ['path' => '/collections/'.$c->slug, 'updated_at' => $c->updated_at?->toIso8601String()]);
        $occasions = Occasion::query()->where('is_published', true)->get(['slug', 'updated_at'])
            ->map(fn ($o) => ['path' => '/occasions/'.$o->slug, 'updated_at' => $o->updated_at?->toIso8601String()]);
        $pages = Page::query()->publiclyVisible()->where('is_indexable', true)->get(['slug', 'updated_at'])
            ->map(fn ($p) => ['path' => '/pages/'.$p->slug, 'updated_at' => $p->updated_at?->toIso8601String()]);
        $lookbooks = Lookbook::query()->publiclyVisible()->get(['slug', 'updated_at'])
            ->map(fn ($l) => ['path' => '/lookbook/'.$l->slug, 'updated_at' => $l->updated_at?->toIso8601String()]);

        return response()->json(['data' => [
            ...$categories, ...$collections, ...$occasions, ...$products, ...$pages, ...$lookbooks,
        ]]);
    }
}
